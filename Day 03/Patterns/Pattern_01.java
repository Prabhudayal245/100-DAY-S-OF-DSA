public class Pattern_01 {
    public static void main(String[] args) {
        for(int i=0;i<4;i++){ // outer loop

            for(int j=0;j<4;j++){  // inner loop
                System.out.print("*");
            }
            
            System.out.println("");
        }
    }
}
