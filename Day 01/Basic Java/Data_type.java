public class Data_type {
    public static void main(String[] args) {
        // int 
        int a=10;  // here int is data type of variable a
        System.out.println("integer:"+a);

        // string
        String place="boisar"; //here String is a datatype of place variable 
        System.out.println("String:"+place);

        // double
        double b=4.5;  // double datatype is used for deecimal variables
        System.out.println("double:"+b);
    }
}
